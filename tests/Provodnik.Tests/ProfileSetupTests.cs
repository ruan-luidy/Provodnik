using Provodnik.Core.Layout;
using Provodnik.Core.Modpack;
using Provodnik.Core.Text;
using Provodnik.Features.ModOrganizer;

namespace Provodnik.Tests
{
  /// <summary>O perfil montado numa pasta GAMMA de mentira: quem é mod da pessoa, a cópia de antes e a base gravada.</summary>
  public sealed class ProfileSetupTests : IDisposable
  {
    private readonly string _root = Path.Combine(Path.GetTempPath(), "provodnik-profile", Guid.NewGuid().ToString("N"));
    private readonly GammaLayout _layout;

    public ProfileSetupTests()
    {
      _layout = new GammaLayout(_root);
      // o profiles_files do GAMMA também traz um modlist.txt (quase vazio)
      Directory.CreateDirectory(_layout.ProfileTemplate);
      File.WriteAllText(Path.Combine(_layout.ProfileTemplate, "modlist.txt"), "# This file was automatically generated by Mod Organizer.\r\n");
      File.WriteAllText(Path.Combine(_layout.ProfileTemplate, "settings.ini"), "[General]\r\n");
    }

    public void Dispose()
    {
      try
      {
        Directory.Delete(_root, recursive: true);
      }
      catch (IOException)
      {
      }
    }

    private string Profile => Path.Combine(_layout.Profiles, ModpackMetadata.Gamma.FolderName, "modlist.txt");

    private string Separator => L.T("features.profile.myMods") + "_separator";

    /// <summary>Pasta de mod; com <paramref name="gammaArchive"/>, o meta.ini que os instaladores do GAMMA escrevem.</summary>
    private void Mod(string name, string? gammaArchive = null, string? meta = null)
    {
      var folder = Path.Combine(_layout.Mods, name);
      Directory.CreateDirectory(folder);
      File.WriteAllText(Path.Combine(folder, "script.txt"), "x");
      if (gammaArchive is not null)
        File.WriteAllText(Path.Combine(folder, "meta.ini"), MetaIni.Build(MetaIni.DefaultTemplate, gammaArchive, null));
      else if (meta is not null)
        File.WriteAllText(Path.Combine(folder, "meta.ini"), meta);
    }

    private void GammaList(params string[] lines)
    {
      var file = Path.Combine(_layout.Definition(ModpackMetadata.Gamma.FolderName), "modpack_data", "modlist.txt");
      Directory.CreateDirectory(Path.GetDirectoryName(file)!);
      File.WriteAllText(file, string.Join("\r\n", lines));
    }

    private void Current(params string[] lines)
    {
      Directory.CreateDirectory(Path.GetDirectoryName(Profile)!);
      File.WriteAllText(Profile, string.Join("\r\n", lines));
    }

    [Fact]
    public void Primeira_vez_separa_os_mods_da_pessoa_dos_restos_do_GAMMA()
    {
      Mod("2- Som - Ana", "som.zip");
      Mod("1- Audio_separator");
      // restos do GAMMA de antes que o launcher original não apaga: mod com o meta.ini dele e separador numerado
      Mod("7- Velho - Caio", "velho.zip");
      Mod("5- Antigos_separator");
      // da pessoa: instalado pelo MO2 (installationFile com caminho, version do mod) e copiado à mão (sem meta.ini)
      Mod("Coop", meta: "[General]\r\nversion=1.4.0.0\r\ninstallationFile=D:/Coop-1.4.zip\r\n");
      Mod("Shuler");
      GammaList("# MO2", "+2- Som - Ana", "+1- Audio_separator");
      Current("# MO2", "+7- Velho - Caio", "+5- Antigos_separator", "-Coop", "+2- Som - Ana", "+Shuler", "+1- Audio_separator");

      var result = ProfileSetup.Apply(_layout, ModpackMetadata.Gamma);

      // as sobras do GAMMA vão desligadas pro começo do MO2 (o fim do arquivo)
      Assert.Equal(["# MO2", "-Coop", "+Shuler", "+" + Separator, "+2- Som - Ana", "+1- Audio_separator", "-7- Velho - Caio", "-5- Antigos_separator"], File.ReadAllText(Profile).Split("\r\n"));
      Assert.Equal(["Coop", "Shuler"], result.Merge.KeptMods);
      Assert.True(File.Exists(Path.Combine(_layout.Mods, Separator, "meta.ini")));
      Assert.NotNull(result.Backup);
      Assert.Contains("+7- Velho - Caio", File.ReadAllText(result.Backup!));
      Assert.Equal(File.ReadAllText(Path.Combine(_layout.Definition(ModpackMetadata.Gamma.FolderName), "modpack_data", "modlist.txt")), File.ReadAllText(ProfileSetup.BasePath(_layout)));
    }

    [Fact]
    public void Pasta_que_o_Provodnik_instalou_nunca_e_da_pessoa()
    {
      // instalada pelo Проводник com a numeração velha, e o meta.ini mexido pelo MO2
      Mod("9- Renumerado - Ana", meta: "[General]\r\nversion=2\r\ninstallationFile=som.zip\r\n");
      Mod("2- Som - Ana", "som.zip");
      GammaList("+2- Som - Ana");
      Current("+9- Renumerado - Ana", "+2- Som - Ana");

      var result = ProfileSetup.Apply(_layout, ModpackMetadata.Gamma, installed: new HashSet<string>(["9- Renumerado - Ana"]));

      Assert.Empty(result.Merge.KeptMods);
      Assert.Equal("+2- Som - Ana\n-9- Renumerado - Ana", File.ReadAllText(Profile));
    }

    [Fact]
    public void Opcional_do_modpack_addons_que_a_pessoa_ligou_fica_ligado()
    {
      var addons = Path.Combine(_layout.Definition(ModpackMetadata.Gamma.FolderName), ModpackMetadata.Gamma.AdditionalFiles);
      Directory.CreateDirectory(Path.Combine(addons, "Sky Fix"));
      Directory.CreateDirectory(Path.Combine(addons, "Bushes Dead"));
      Mod("Sky Fix");
      Mod("Bushes Dead");
      Mod("2- Som - Ana", "som.zip");
      GammaList("+2- Som - Ana");
      Current("+Sky Fix", "+2- Som - Ana");

      var result = ProfileSetup.Apply(_layout, ModpackMetadata.Gamma);

      // o desligado sem linha ganha uma no começo do MO2; sem ela o MO2 poria ele no "Meus mods"
      Assert.Equal(["+Sky Fix", "+" + Separator, "+2- Som - Ana", "-Bushes Dead"], File.ReadAllText(Profile).Split("\n"));
      Assert.Equal(["Sky Fix"], result.Merge.KeptMods);
    }

    [Fact]
    public void A_base_gravada_guarda_o_que_a_pessoa_desligou_na_proxima()
    {
      Mod("2- Som - Ana", "som.zip");
      Mod("3- Luz - Bia", "luz.zip");
      GammaList("+3- Luz - Bia", "+2- Som - Ana");
      ProfileSetup.Apply(_layout, ModpackMetadata.Gamma);

      // a pessoa desliga o Som no MO2; o GAMMA atualiza e põe um mod novo
      Current("+3- Luz - Bia", "-2- Som - Ana");
      Mod("4- Novo - Caio", "novo.zip");
      GammaList("+4- Novo - Caio", "+3- Luz - Bia", "+2- Som - Ana");
      var result = ProfileSetup.Apply(_layout, ModpackMetadata.Gamma);

      Assert.Equal("+4- Novo - Caio\r\n+3- Luz - Bia\r\n-2- Som - Ana", File.ReadAllText(Profile));
      Assert.Equal(["2- Som - Ana"], result.Merge.KeptChoices);
    }

    [Fact]
    public void Sem_mudanca_nao_faz_copia()
    {
      Mod("2- Som - Ana", "som.zip");
      Mod("Shuler");
      GammaList("+2- Som - Ana");
      Current("+Shuler", "+2- Som - Ana");

      var first = ProfileSetup.Apply(_layout, ModpackMetadata.Gamma);
      var second = ProfileSetup.Apply(_layout, ModpackMetadata.Gamma);

      Assert.NotNull(first.Backup);
      Assert.Null(second.Backup);
      Assert.Single(Directory.GetFiles(ProfileSetup.BackupsDir(_layout)));
    }

    [Fact]
    public void Guarda_so_as_ultimas_dez_copias()
    {
      var dir = ProfileSetup.BackupsDir(_layout);
      Directory.CreateDirectory(dir);
      for (var i = 0; i < 12; i++)
        File.WriteAllText(Path.Combine(dir, $"modlist-20200101-0000{i:00}.txt"), "velho");
      Mod("2- Som - Ana", "som.zip");
      Mod("Shuler");
      GammaList("+2- Som - Ana");
      Current("+Shuler", "+2- Som - Ana");

      var result = ProfileSetup.Apply(_layout, ModpackMetadata.Gamma);

      var kept = Directory.GetFiles(dir);
      Assert.Equal(10, kept.Length);
      Assert.Contains(result.Backup, kept);
    }
  }
}
