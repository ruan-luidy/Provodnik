using Provodnik.Core.Modpack;

namespace Provodnik.Tests
{
  public class Mo2ModListTests
  {
    [Fact]
    public void Ativos_sao_os_ligados_sem_separador()
    {
      const string text = "# This file was automatically generated by Mod Organizer.\r\n" +
        "+G.A.M.M.A. End of List_separator\r\n" +
        "+335- Auto-Stacking Items - Zatura\r\n" +
        "-ZCP 1.5d\r\n" +
        "+G.A.M.M.A. New Main Menu\r\n" +
        "*DLC travado\r\n";

      var list = Mo2ModList.Parse(text);

      Assert.Equal(5, list.Entries.Count);
      Assert.Equal(["335- Auto-Stacking Items - Zatura", "G.A.M.M.A. New Main Menu", "DLC travado"], list.ActiveMods.Select(m => m.Name));
    }
  }
}
