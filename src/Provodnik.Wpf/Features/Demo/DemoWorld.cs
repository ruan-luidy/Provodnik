using System.IO;
using System.Security.Cryptography;
using System.Text;
using Provodnik.Core.Modpack;

namespace Provodnik.Wpf.Features.Demo
{
  /// <summary>
  /// O mundo da simulação (--demo): uma pasta GAMMA de mentira em %TEMP%\provodnik-demo com a lista de mods de verdade
  /// (os 473 nomes, embutidos no exe), pra ver a instalação inteira (download, bloqueio do ModDB, falha, extração,
  /// conferência) sem baixar nada e sem encostar no GAMMA de verdade. O md5 da lista é trocado pelo md5 do conteúdo
  /// que o download falso escreve, pra conferência passar como passaria de verdade.
  /// </summary>
  public sealed class DemoWorld
  {
    public const string Flag = "--demo";

    public static string Home { get; } = Path.Combine(Path.GetTempPath(), "provodnik-demo");

    public static bool Requested(IEnumerable<string> args) => args.Contains(Flag);

    public string Root { get; } = Path.Combine(Home, "GAMMA");

    public string AppData { get; } = Path.Combine(Home, "appdata");

    public string ListText { get; }

    public ModList List { get; }

    /// <summary>Arquivo → as pastas que as instruções esperam dentro dele (o 7z falso cria elas).</summary>
    public IReadOnlyDictionary<string, IReadOnlyList<string>> Folders { get; }

    public DemoWorld()
    {
      ListText = WithDemoMd5(LoadList());
      List = ModList.Parse(ListText);
      Folders = List.Mods
        .Where(m => m.ArchiveName is not null)
        .GroupBy(m => m.ArchiveName!, StringComparer.OrdinalIgnoreCase)
        .ToDictionary(g => g.Key, g => (IReadOnlyList<string>)g.SelectMany(m => m.Instructions).Distinct().ToList(), StringComparer.OrdinalIgnoreCase);
    }

    /// <summary>O conteúdo que o download falso grava (e o md5 que a lista passa a esperar).</summary>
    public static string ContentOf(string archiveName) => $"demo:{archiveName}";

    /// <summary>Um número estável por nome: decide tamanho, velocidade e quem falha, igual a cada rodada.</summary>
    public static int Dice(string name, int salt = 0)
    {
      var hash = MD5.HashData(Encoding.UTF8.GetBytes($"{salt}:{name}"));
      return BitConverter.ToInt32(hash, 0) & int.MaxValue;
    }

    /// <summary>A pasta GAMMA falsa com o mínimo que a checagem e o pipeline procuram. Reset: começa do zero.</summary>
    public void Prepare(bool reset)
    {
      if (reset && Directory.Exists(Root))
        Directory.Delete(Root, recursive: true);

      var installer = Path.Combine(Root, Core.Layout.GammaLayout.InstallerFolderName);
      var resources = Path.Combine(installer, "resources");
      foreach (var tool in new[] { @"7zip\7z.exe", @"curl-impersonate-win\curl.exe", @"curl-impersonate-win\config\safari15_5.config", @"curl-impersonate-win\config\safari15_5.header", @"cmd\git.exe", "stalker-gamma-dl-cli.exe" })
        Touch(Path.Combine(resources, tool), string.Empty);
      Touch(Path.Combine(resources, "meta.ini"), MetaIni.DefaultTemplate);
      Touch(Path.Combine(resources, @"separator\meta.ini"), MetaIni.SeparatorTemplate);
      foreach (var file in new[] { "archives.txt", "initweaks.ini", "lockedorder.txt", "modlist.txt", "settings.ini" })
        Touch(Path.Combine(resources, "profiles_files", file), string.Empty);
      Touch(Path.Combine(installer, "modpack_maker_metadata.txt"), "author = Grokitach\nmodpack name = G.A.M.M.A.\nmodpack maker list = modpack_data/modpack_maker_list.txt\nModOrganier2 modlist = modpack_data/modlist.txt\nmodpack additional files = modpack_addons\n");
      Touch(Path.Combine(Root, "ModOrganizer.exe"), string.Empty);

      var anomaly = Path.Combine(Home, "Anomaly");
      Directory.CreateDirectory(Path.Combine(anomaly, "bin"));
      var game = anomaly.Replace(@"\", @"\\");
      Touch(Path.Combine(Root, "ModOrganizer.ini"),
        $"[General]\ngameName=STALKER Anomaly\ngamePath=@ByteArray({game})\nselected_profile=@ByteArray(G.A.M.M.A)\n" +
        $"[customExecutables]\n1\\binary={anomaly.Replace('\\', '/')}/AnomalyLauncher.exe\n1\\title=Anomaly Launcher\n" +
        $"2\\binary={anomaly.Replace('\\', '/')}/bin/AnomalyDX11AVX.exe\n2\\title=Anomaly (DX11-AVX)\n" +
        $"3\\binary={anomaly.Replace('\\', '/')}/bin/AnomalyDX11.exe\n3\\title=Anomaly (DX11)\n");
      Directory.CreateDirectory(AppData);
    }

    /// <summary>O modlist.txt da definição: todo mod e separador ligado, na ordem inversa como o MO2 grava.</summary>
    public string ModOrganizerList() =>
      "# This file was automatically generated by Mod Organizer.\r\n" +
      string.Join("\r\n", List.Entries.Where(e => e.Name.Trim().Length > 0).Reverse().Select(e => "+" + e.FolderName)) + "\r\n";

    private static string LoadList()
    {
      using var stream = typeof(DemoWorld).Assembly.GetManifestResourceStream("Provodnik.demo-mods.txt")
        ?? throw new InvalidOperationException("A lista da simulação não foi embutida no exe.");
      using var reader = new StreamReader(stream);
      return reader.ReadToEnd();
    }

    private static string WithDemoMd5(string text)
    {
      var lines = text.Replace("\r\n", "\n").Split('\n');
      for (var i = 0; i < lines.Length; i++)
      {
        var columns = lines[i].Split('\t');
        if (columns.Length < 7 || !columns[0].Contains("moddb", StringComparison.OrdinalIgnoreCase))
          continue;
        columns[6] = Convert.ToHexStringLower(MD5.HashData(Encoding.UTF8.GetBytes(ContentOf(columns[5].Trim()))));
        lines[i] = string.Join('\t', columns);
      }
      return string.Join('\n', lines);
    }

    private static void Touch(string path, string content)
    {
      Directory.CreateDirectory(Path.GetDirectoryName(path)!);
      if (!File.Exists(path))
        File.WriteAllText(path, content);
    }
  }
}
